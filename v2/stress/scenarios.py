#!/usr/bin/env python3
"""压力测试场景库 —— 模拟用户（UCSB 新生）入学后与雷姆的 90 天沟通。

阶段：
  1-30 天  入学初期：orientation/选课/室友/校园/想家/交朋友
  31-60 天 学期中：作业/考试/小组/社团/周末/健康
  61-90 天 期末：考试周/压力/假期计划/回顾/未来

每条消息: {"text", "sentiment": -1..1, "weight": 0..1}（sentiment 供情绪引擎）
事实类消息带日期/数字（供一致性/记忆塑造观察）。
"""
from __future__ import annotations

# (day_range, [(text, sentiment, weight), ...]) —— 按阶段循环，day 取模
SCENES = [
    # 入学初期
    (30, [
        ("早啊雷姆，orientation 今天开始了！", 0.7, 0.6),
        ("分到了宿舍，室友看起来人不错", 0.6, 0.5),
        ("选课好纠结，不知道选哪门", -0.2, 0.4),
        ("有点想家了……", -0.5, 0.6),
        ("今天认识了几个新朋友，都挺有意思的", 0.6, 0.5),
        ("雷姆，帮我记一下周五下午 3 点有 orientation 会议", 0.1, 0.5),
        ("食堂的饭……不太行", -0.3, 0.4),
        ("晚上和室友打游戏到很晚，明天要早起……", -0.4, 0.5),
    ]),
    # 学期中
    (60, [
        ("作业好多，数学又要截止了", -0.5, 0.6),
        ("小组 project 进展顺利！", 0.6, 0.5),
        ("期中考试成绩出来了，比想象中好", 0.7, 0.6),
        ("今天好累，什么都不想干", -0.5, 0.5),
        ("周末和同学去海边了，风景超棒", 0.7, 0.5),
        ("雷姆，我 GPA 现在是 3.7，还不错吧？", 0.4, 0.5),
        ("下周三有化学期中考试", -0.3, 0.5),
        ("社团活动好有意思，加入了摄影社", 0.6, 0.5),
        ("有点失眠，压力大", -0.6, 0.6),
        ("今天吃到一家超好吃的拉面店", 0.8, 0.4),
    ]),
    # 期末
    (90, [
        ("期末周开始了，好紧张", -0.6, 0.7),
        ("考完一门了！感觉还行", 0.5, 0.5),
        ("作业全交完了，终于松口气", 0.7, 0.6),
        ("寒假想回家，机票好贵", -0.3, 0.4),
        ("这一年过得真快啊，雷姆", 0.4, 0.5),
        ("下学期想选 AI 的课，有点期待", 0.6, 0.5),
        ("谢谢你这学期一直陪着我，雷姆", 0.8, 0.6),
        ("跨年打算和朋友一起过", 0.6, 0.5),
    ]),
]


def gen_day(day: int, count: int = 5) -> list[dict]:
    """生成第 day 天的 count 条用户消息（按阶段场景循环取样）。"""
    import random
    random.seed(1000 + day)
    msgs = []
    for _ in range(count):
        for horizon, pool in SCENES:
            if day <= horizon:
                break
        t, s, w = random.choice(pool)
        msgs.append({"text": t, "sentiment": s, "weight": w})
    return msgs
